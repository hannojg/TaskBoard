import assert from 'node:assert/strict';
import { mkdtempSync,rmSync,writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join,resolve } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { sharedFixture } from '../tests/support/shared.mjs';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
const temp = tmpdir(); const directory = mkdtempSync(join(temp,'taskboard-mcp-'));
const cleanups = [];
const fixture = await sharedFixture({after:cleanup => cleanups.push(cleanup)});
const testClient = fixture.client();
const connectionPath = join(directory,'connection.json');
const connectionText = JSON.stringify(testClient.connection);
writeFileSync(connectionPath,connectionText);
const server = resolve('dist/server.mjs');
const transport = new StdioClientTransport({command:process.execPath,args:[server],env:{...process.env,TASKBOARD_DATA_DIR:directory},stderr:'pipe'});
const client = new Client({name:'taskboard-smoke',version:'1.0.0'});
function data(result) { assert.notEqual(result.isError,true); return result.structuredContent; }
try {
 await client.connect(transport);
 const list = await client.listTools(); assert.ok(list.tools.some(tool => tool.name === 'taskboard_open'));
 const sidebar = list.tools.find(tool => tool.name === 'taskboard_open');
 assert.equal(sidebar.title,'TaskBoard');
 assert.deepEqual(sidebar._meta['openai/ui'].entrypoints,[{type:'global'}]);
 const panel = list.tools.find(tool => tool.name === 'taskboard_open_panel');
 assert.equal(panel.title,'TaskBoard');
 assert.deepEqual(panel._meta['openai/ui'].entrypoints,[{type:'thread'}]);
 assert.notEqual(sidebar._meta.ui.resourceUri,panel._meta.ui.resourceUri);
 const globalResource = await client.readResource({uri:sidebar._meta.ui.resourceUri});
 assert.equal(globalResource.contents[0]._meta['openai/ui'].preferredDisplayMode,'fullscreen');
 const panelResource = await client.readResource({uri:panel._meta.ui.resourceUri});
 assert.equal(panelResource.contents[0]._meta['openai/ui'].preferredDisplayMode,'inline');
 const opened = await client.callTool({name:'taskboard_open',arguments:{}}); const launch = data(opened); assert.equal(launch.connectionRequired,false);
 const initialRead = await client.callTool({name:'taskboard_read',arguments:{}}); let board = data(initialRead); assert.equal(board.revision,0);
 const resource = await client.readResource({uri:'ui://taskboard/0.10.3/board.html'}); assert.match(resource.contents[0].text,/description-editor/);
 assert.ok(resource.contents[0]._meta.ui.csp.resourceDomains.includes('https://*'));
 assert.ok(resource.contents[0]._meta.ui.csp.resourceDomains.includes('data:'));
 const synced = await client.callTool({name:'taskboard_sync_projects',arguments:{projects:[{projectId:'verified-p',label:'Example',path:'/repo',hostId:'local',isGitRepository:true}]}}); board = data(synced); assert.equal(board.catalog.length,1);
 const chatSync = await client.callTool({name:'taskboard_sync_chats',arguments:{chats:[{threadId:'confirmed-chat',hostId:'local',title:'Confirmed chat',projectId:'verified-p'}]}}); board = data(chatSync); assert.equal(board.chatCatalog.length,1);
 const project = {id:'p',name:'Example',repo:'',path:'/repo',codexId:'verified-p',hostId:'local',chat:''};
 const added = await client.callTool({name:'taskboard_upsert_project',arguments:{project,revision:board.revision}}); board = data(added);
 const task = {id:'t',title:'Test ticket',description:'**bold**\n\n![Screenshot](data:image/png;base64,YWJj)',priority:'None',due:'',projectId:'p',statusId:'backlog',chats:[{threadId:'confirmed-chat',hostId:'local',title:'Confirmed chat',url:''}],references:[{url:'https://example.slack.com/archives/C123ABC/p1793360999654321?thread_ts=1793360123.123456&cid=C123ABC',title:'Store upload request'}]};
 const created = await client.callTool({name:'taskboard_upsert_task',arguments:{task,revision:board.revision}}); board = data(created); assert.equal(board.state.tasks[0].chats[0].threadId,'confirmed-chat');
 const stale = await client.callTool({name:'taskboard_save',arguments:{state:board.state,revision:0}}); assert.equal(stale.isError,true);
 const current = await client.callTool({name:'taskboard_read',arguments:{}}); const saved = data(current); assert.equal(saved.state.tasks.length,1);
 assert.equal(saved.state.tasks[0].description,task.description);
 assert.deepEqual(saved.state.tasks[0].references,[{url:'https://example.slack.com/archives/C123ABC/p1793360123123456',title:'Store upload request'}]);
 assert.equal(saved.boardUrl,testClient.connection.url);
 const asanaImport = list.tools.find(tool => tool.name === 'taskboard_import_asana');
 assert.deepEqual(asanaImport._meta.ui.visibility,['model']);
 const source = {gid:'1234567890123456',url:'https://app.asana.com/1/100/task/1234567890123456',title:'Asana source',description:'Source description',modifiedAt:'2026-10-30T10:00:00Z'};
 const imported = await client.callTool({name:'taskboard_import_asana',arguments:{source,projectId:'p',statusId:'todo',revision:saved.revision}});
 const linked = data(imported);
 const asanaTask = linked.state.tasks.find(item => item.id === linked.importedTaskId);
 assert.equal(asanaTask.asana.gid,source.gid);
 const fresh = {...source,title:'Updated through Asana',description:'Updated source',modifiedAt:'2026-10-30T11:00:00Z'};
 const refreshed = await client.callTool({name:'taskboard_sync_asana',arguments:{tasks:[fresh],revision:linked.revision}});
 const updated = data(refreshed);
 const asanaUpdated = updated.state.tasks.find(item => item.id === asanaTask.id);
 assert.equal(asanaUpdated.title,fresh.title);
 assert.equal(asanaUpdated.description,fresh.description);
 const localEdit = {...asanaUpdated,title:'Local overwrite',description:'Local overwrite',chats:task.chats};
 const edited = await client.callTool({name:'taskboard_upsert_task',arguments:{task:localEdit,revision:updated.revision}});
 const protectedBoard = data(edited);
 const protectedTask = protectedBoard.state.tasks.find(item => item.id === asanaTask.id);
 assert.equal(protectedTask.title,fresh.title);
 assert.equal(protectedTask.description,fresh.description);
 assert.equal(protectedTask.chats.length,1);
 console.log('Asana MCP: import, source refresh, ownership protection and chat linking passed.');
 console.log('Named sidebar and chat entrypoints verified. MCP: resource, catalog sync, project creation, task linking, references, persistence and conflict checks passed.');
} finally { await client.close(); for (const cleanup of cleanups) await cleanup(); rmSync(directory,{recursive:true}); }
